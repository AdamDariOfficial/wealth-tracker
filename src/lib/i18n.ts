export function normalizeAppLocale(value: string | null | undefined): AppLocale {
  return value === "it-IT" ? "it-IT" : "en-US";
}

export function tr(locale: string | null | undefined, text: string): string {
  return normalizeAppLocale(locale) === "it-IT" ? (ITALIAN[text] ?? text) : text;
}
